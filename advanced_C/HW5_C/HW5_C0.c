/*Вычеркивание
Сколько различных трехзначных чисел можно получить из заданного натурального N, вычеркивая цифры из его десятичной записи?*/

#include <stdio.h>

int main(void) {
    char n[100001];
    int used[1000] = {0};
    int count = 0;

    scanf("%100000s", n);

    // Выбираем первую цифру
    for (int i = 0; n[i] != '\0'; i++) {

        // Выбираем вторую цифру
        for (int j = i + 1; n[j] != '\0'; j++) {

            // Выбираем третью цифру
            for (int k = j + 1; n[k] != '\0'; k++) {

                // Трёхзначное число не может начинаться с нуля
                if (n[i] == '0') {
                    continue;
                }

                int number =
                    (n[i] - '0') * 100 +
                    (n[j] - '0') * 10 +
                    (n[k] - '0');

                // Проверяем, встречалось ли число раньше
                if (used[number] == 0) {
                    used[number] = 1;
                    count++;
                }
            }
        }
    }

    printf("%d\n", count);

    return 0;
}
