/*Инверсия старший
    На вход программе подается беззнаковое 32-битное целое число N. 
    Требуется изменить значения всех битов старшего байта числа на противоположные и вывести полученное таким образом число.*/

#include <stdio.h>
#include <stdint.h>

int main(void) {
    uint32_t N;

    scanf("%u", &N);

    N ^= (0xFFu << 24);

    printf("%u\n", N);

    return 0;
}